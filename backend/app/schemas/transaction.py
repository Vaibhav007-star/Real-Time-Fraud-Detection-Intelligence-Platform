from datetime import datetime, timezone
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field, validator


class CompatBaseModel(BaseModel):
    def to_dict(self) -> Dict[str, Any]:
        if hasattr(self, "model_dump"):
            return self.model_dump()
        return self.dict()


VALID_CURRENCIES = {"USD", "EUR", "GBP", "INR", "CAD", "SGD", "JPY", "AUD"}
VALID_TX_TYPES = {"PURCHASE", "TRANSFER", "WITHDRAWAL", "WIRE", "CARD_NOT_PRESENT", "CRYPTO_EXCHANGE"}
VALID_TX_STATUS = {"COMPLETED", "PENDING", "FAILED", "DECLINED"}


class TransactionCreate(CompatBaseModel):
    transaction_id: str = Field(..., min_length=3, max_length=128, description="Unique transaction identifier")
    timestamp: str = Field(..., description="ISO-8601 event occurrence timestamp")
    source_account_id: str = Field(..., min_length=2, max_length=64, description="Originating account ID")
    destination_account_id: Optional[str] = Field(None, max_length=64, description="Destination account ID for transfers")
    merchant_id: Optional[str] = Field(None, max_length=64, description="Merchant identifier for purchases")
    merchant_category: Optional[str] = Field("GENERAL_RETAIL", max_length=64, description="Merchant category code/label")
    device_id: str = Field(..., min_length=2, max_length=64, description="Device fingerprint or synthetic ID")
    ip_address: str = Field(..., min_length=3, max_length=64, description="Privacy-safe IP hash or subnet representation")
    transaction_amount: float = Field(..., description="Transaction monetary amount (> 0)")
    currency: str = Field("USD", max_length=8, description="ISO currency code")
    transaction_type: str = Field("PURCHASE", max_length=32, description="Transaction type")
    location: Optional[str] = Field("US-NY", max_length=64, description="Geographic region or city code")
    transaction_status: str = Field("COMPLETED", max_length=32, description="Transaction execution status")
    fraud_label: Optional[int] = Field(None, description="Optional ground-truth label (0 or 1) used ONLY for evaluation, never exposed to model inference")
    is_demo: bool = Field(False, description="True if generated by synthetic demo stream or scenario")
    scenario_tag: Optional[str] = Field(None, max_length=64, description="Optional demo scenario label")

    @validator("transaction_amount")
    def validate_positive_amount(cls, v: float) -> float:
        if v is None or v <= 0 or v > 1e9:
            raise ValueError("transaction_amount must be greater than 0 and at most 1,000,000,000")
        return round(float(v), 2)

    @validator("currency")
    def validate_currency(cls, v: str) -> str:
        code = (v or "USD").upper().strip()
        if code not in VALID_CURRENCIES:
            raise ValueError(f"Unsupported currency '{code}'. Supported: {sorted(VALID_CURRENCIES)}")
        return code

    @validator("transaction_type")
    def validate_tx_type(cls, v: str) -> str:
        t = (v or "PURCHASE").upper().strip()
        if t not in VALID_TX_TYPES:
            raise ValueError(f"Unsupported transaction_type '{t}'. Supported: {sorted(VALID_TX_TYPES)}")
        return t

    @validator("transaction_status")
    def validate_tx_status(cls, v: str) -> str:
        s = (v or "COMPLETED").upper().strip()
        if s not in VALID_TX_STATUS:
            raise ValueError(f"Unsupported transaction_status '{s}'. Supported: {sorted(VALID_TX_STATUS)}")
        return s

    @validator("timestamp")
    def validate_timestamp(cls, v: str) -> str:
        if not v or not str(v).strip():
            raise ValueError("timestamp cannot be empty")
        raw = str(v).strip()
        try:
            if raw.endswith("Z"):
                raw = raw[:-1] + "+00:00"
            dt = datetime.fromisoformat(raw)
            if dt.tzinfo is None:
                dt = dt.replace(tzinfo=timezone.utc)
            return dt.astimezone(timezone.utc).isoformat()
        except Exception as exc:
            raise ValueError(f"Invalid ISO-8601 timestamp '{v}': {exc}")

    @validator("fraud_label")
    def validate_fraud_label(cls, v: Optional[int]) -> Optional[int]:
        if v is not None and v not in (0, 1):
            raise ValueError("fraud_label must be 0, 1, or None")
        return v


class ScoredTransactionResponse(CompatBaseModel):
    transaction_id: str
    event_timestamp: str
    ingestion_timestamp: str
    scoring_timestamp: str
    source_account_id: str
    destination_account_id: Optional[str] = None
    merchant_id: Optional[str] = None
    merchant_category: Optional[str] = None
    device_id: str
    ip_address: str
    transaction_amount: float
    currency: str
    transaction_type: str
    location: Optional[str] = None
    transaction_status: str
    fraud_label: Optional[int] = None
    is_demo: bool = False
    scenario_tag: Optional[str] = None
    is_late_event: bool = False
    late_by_seconds: float = 0.0
    ml_score: float
    graph_score: float
    rule_score: float
    combined_score: float
    risk_percentage: float
    risk_category: str  # LOW_RISK, REVIEW, HIGH_RISK
    predicted_class: int
    model_version: str
    scoring_method: str
    scoring_status: str
    warnings: List[str] = []
    triggered_rules: List[str] = []
    top_risk_factors: List[Dict[str, Any]] = []
    graph_explanations: List[str] = []
    features: Dict[str, float] = {}
    alert_id: Optional[str] = None
    processing_latency_ms: float = 0.0
